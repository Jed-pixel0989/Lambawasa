as $$
declare
  metadata jsonb := new.raw_user_meta_data;
  consumer_id bigint;
  code_suffix text := replace(new.id::text, '-', '');
  consumer_latitude numeric(10, 6);
  consumer_longitude numeric(10, 6);
  consumer_zone text := coalesce(nullif(metadata ->> 'zone', ''), 'Mabuhay');
  meter_code text := 'MTR-' || upper(substr(replace(new.id::text, '-', ''), 25, 8));
begin
  if metadata ->> 'app_role' <> 'House Hold' then
    return new;
  end if;

  if nullif(metadata ->> 'full_name', '') is null
    or nullif(metadata ->> 'contact_no', '') is null
    or nullif(metadata ->> 'service_address', '') is null then
    raise exception 'Household registration is missing required profile details.';
  end if;

  consumer_latitude := nullif(metadata ->> 'latitude', '')::numeric;
  consumer_longitude := nullif(metadata ->> 'longitude', '')::numeric;

  insert into public.consumers (
    auth_user_id, consumer_code, account_no, username, email, full_name,
    contact_no, service_address, zone, classification, meter_serial,
    status, approval_status, location_approval_status,
    requested_latitude, requested_longitude, connection_date
  ) values (
    new.id,
    'C-' || upper(substr(code_suffix, 1, 12)),
    'ACC-' || upper(substr(code_suffix, 13, 12)),
    lower(metadata ->> 'username'),
    lower(new.email),
    metadata ->> 'full_name',
    metadata ->> 'contact_no',
    metadata ->> 'service_address',
    consumer_zone,
    coalesce(nullif(metadata ->> 'classification', ''), 'Residential'),
    meter_code,
    'Pending',
    'Pending',
    case when consumer_latitude is not null and consumer_longitude is not null then 'Approved' else 'None' end,
    consumer_latitude,
    consumer_longitude,
    current_date
  )
  returning id into consumer_id;

  insert into public.meter_assets (
    serial_no, brand, model, install_date, consumer_id, zone,
    last_calibration, next_calibration, status
  ) values (
    meter_code, 'Aquaflow Pro', 'AF-20-Brass', current_date, consumer_id,
    consumer_zone, current_date, current_date + interval '2 years', 'Active'
  );

  if consumer_latitude is not null and consumer_longitude is not null then
    insert into public.geo_connections (consumer_id, zone, latitude, longitude)
    values (consumer_id, consumer_zone, consumer_latitude, consumer_longitude);
